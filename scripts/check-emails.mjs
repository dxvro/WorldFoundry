#!/usr/bin/env node
// Fails when a tracked file or a commit contains an email address other than the project's contact address,
// a no-reply address or a documented placeholder. Run by `npm test` and by CI.
//
//   node scripts/check-emails.mjs            tracked files and the whole history of the current branch
//   node scripts/check-emails.mjs --files    tracked files only
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { forbiddenInCommit, forbiddenInFile } from './lib/emails.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const git = (...args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });

// generated by npm: integrity hashes and registry metadata, no hand-written text
const SKIP = new Set(['package-lock.json']);

const problems = [];

let inRepository = true;
try {
  git('rev-parse', '--git-dir');
} catch {
  inRepository = false;
}

if (!inRepository) {
  // an unpacked source archive: nothing to list and no history to read
  console.log('check-emails: not a git checkout, skipped.');
  process.exit(0);
}

for (const file of git('ls-files', '-z').split('\0')) {
  if (file === '' || SKIP.has(file)) continue;
  let buffer;
  try {
    buffer = readFileSync(path.join(ROOT, file));
  } catch {
    continue; // deleted in the working tree
  }
  if (buffer.includes(0)) continue; // binary
  const lines = buffer.toString('utf8').split('\n');
  lines.forEach((line, index) => {
    for (const address of forbiddenInFile(line)) problems.push(`${file}:${index + 1}: ${address}`);
  });
}

if (!process.argv.includes('--files')) {
  let log = '';
  try {
    log = git('log', '--format=%H%x1f%ae%x1f%ce%x1f%B%x1e');
  } catch {
    log = ''; // no commit yet
  }
  for (const record of log.split('\x1e')) {
    const [hash, author, committer, body] = record.trim().split('\x1f');
    if (hash === undefined || hash === '') continue;
    for (const address of forbiddenInCommit(`${author} ${committer}`)) problems.push(`commit ${hash.slice(0, 10)}: author or committer ${address}`);
    for (const address of forbiddenInCommit(body ?? '')) problems.push(`commit ${hash.slice(0, 10)}: message mentions ${address}`);
  }
}

if (problems.length > 0) {
  console.error('Email addresses that must not be in this repository:\n');
  for (const problem of problems) console.error(`  ${problem}`);
  console.error('\nOnly the contact address, no-reply addresses and placeholder domains (example.com, *.invalid, *.test) are allowed.');
  console.error('See scripts/lib/emails.mjs. For commits: set "git config user.email" to your GitHub no-reply address.');
  process.exit(1);
}
console.log('check-emails: no private email address in the files or the history.');
